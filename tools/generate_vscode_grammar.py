#!/usr/bin/env python3
"""Generate Bo syntax artifacts for VS Code and JupyterLab."""

import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from python.bo.lower import lower_op_forms
from python.bo.values import Op
from bodoc import DERIVED_SOURCES, parse_derived
from generate_adapters import native_names


CORE_LIBRARY = ROOT / "include" / "core.bo"
GRAMMAR = ROOT / "vscode" / "syntaxes" / "bo.tmLanguage.json"
JUPYTER_LANGUAGE = ROOT / "jupyterlab" / "src" / "generated.ts"


def primitive_names():
    return [name for name in native_names() if "." not in name]


def primitive_actions():
    return list(dict.fromkeys(name.rpartition(".")[2] for name in native_names()))


def adapter_names(path):
    items = [
        item
        for _, form in lower_op_forms(path.read_text(encoding="utf-8"))
        for item in form
    ]
    names = []
    for definition, selector, action in zip(items, items[1:], items[2:]):
        if (action == Op("PUSH") and isinstance(definition, list)
                and isinstance(selector, list) and len(selector) == 1
                and isinstance(selector[0], Op)):
            names.append(selector[0].name)
    return names


def library_ops():
    names = adapter_names(CORE_LIBRARY)
    for path in DERIVED_SOURCES:
        names.extend(entry["name"] for entry in parse_derived(path))
    return list(dict.fromkeys(names))


def op_pattern(ops):
    return rf'(?<![^\s()"])(?:{"|".join(re.escape(op) for op in ops)})(?![^\s()"])'


def qualified_action_pattern(actions):
    return rf'(?<=\.)(?:{"|".join(re.escape(action) for action in actions)})(?![^\s()"])'


def is_qualified(op):
    """A dotted op such as `Stack.dup`; ops starting with a dot (`.`, `.5`-like) are not."""
    return "." in op and not op.startswith(".")


def qualified_actions(ops):
    """Names that may follow a qualifier: the last segment of every op not starting with a dot."""
    return list(dict.fromkeys(
        op.rpartition(".")[2] for op in ops if not op.startswith(".")
    ))


def updated_grammar():
    grammar = json.loads(GRAMMAR.read_text(encoding="utf-8"))
    repository = grammar["repository"]
    repository["primitive"]["match"] = (
        qualified_action_pattern(primitive_actions())
        + "|"
        + op_pattern(primitive_names())
    )
    adapters = library_ops()
    repository["adapter"]["match"] = (
        op_pattern([adapter for adapter in adapters if not is_qualified(adapter)])
        + "|"
        + qualified_action_pattern(qualified_actions(adapters))
    )
    return json.dumps(grammar, indent=2, ensure_ascii=False) + "\n"


def typescript_strings(values):
    return ",\n".join(f"  {json.dumps(value)}" for value in values)


def updated_jupyter_language():
    return (
        "/* This file is generated by tools/generate_vscode_grammar.py. */\n\n"
        "export const primitiveActions = new Set<string>([\n"
        + typescript_strings(primitive_actions())
        + "\n]);\n\n"
        "export const primitiveNames = new Set<string>([\n"
        + typescript_strings(primitive_names())
        + "\n]);\n\n"
        "export const adapterNames = new Set<string>([\n"
        + typescript_strings(library_ops())
        + "\n]);\n"
    )


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true",
                        help="fail if the committed syntax artifacts are not generated")
    args = parser.parse_args()
    generated = updated_grammar()
    generated_jupyter = updated_jupyter_language()
    current = GRAMMAR.read_text(encoding="utf-8")
    current_jupyter = JUPYTER_LANGUAGE.read_text(encoding="utf-8") if JUPYTER_LANGUAGE.exists() else None
    if args.check:
        stale = []
        if current != generated:
            stale.append(GRAMMAR)
        if current_jupyter != generated_jupyter:
            stale.append(JUPYTER_LANGUAGE)
        if stale:
            paths = ", ".join(str(path.relative_to(ROOT)) for path in stale)
            print(f"{paths} are stale; run {Path(__file__).relative_to(ROOT)}", file=sys.stderr)
            return 1
        return 0
    GRAMMAR.write_text(generated, encoding="utf-8")
    JUPYTER_LANGUAGE.parent.mkdir(parents=True, exist_ok=True)
    JUPYTER_LANGUAGE.write_text(generated_jupyter, encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
